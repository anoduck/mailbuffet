def get_mbox(mbox_file):
    return mbox(mbox_file, create=False)


def write_table(table, filepath):
    mdtbl = markdown_table(table).set_params(row_sep='markdown', quote=False).get_markdown()
    with open(filepath, 'w', encoding='utf-8') as wt:
        wt.write(mdtbl)
        wt.close()
    print('Index written to file')


def write_csv(field_names, table, outdir):
    csvfile = outdir + '/index.csv'
    with open(csvfile, 'w') as cw:
        writer = csv.DictWriter(cw, fieldnames = field_names)
        writer.writeheader()
        writer.writerows(table)


def check_filepath(path, outdir):
    if path is not None:
        splitpath = path.split('/')
        basepath = splitpath.pop()
        realpath = outdir + '/' + basepath
        if os.path.isfile(realpath):
            path = path
        else:
            path = None
    else:
        path = None
    return path


def checklink(path, outdir):
    if path is None:
        return None
    else:
        path = check_filepath(path, outdir)
        return path


def generate_index(msg_list, outdir, webpath, log):
    filename = 'index.md'
    filepath = os.path.join(outdir, filename)
    log.debug(f'File path for file: {filepath}')
    table = []
    for msg in msg_list:
        fname = get_filename(msg)
        fpath = os.path.join(outdir, fname)
        if not os.path.exists(fpath):
            continue
        if isreply(msg):
            replyto = get_replylink(msg, webpath, outdir)
        else:
            replyto = None
        if hasrefs(msg):
            refs = get_reflinks(msg, webpath, outdir)
        else:
            refs = None
        flink = get_selflink(msg, webpath, outdir)
        log.debug(f'{flink}')
        parent_subject = get_subject(msg)
        parent_date = get_date(msg)
        tbl_row = {"Subject": parent_subject,
                    "Date": parent_date,
                    "Path": flink,
                    "Reply-to": replyto,
                    "Refs": refs}
        table.append(tbl_row)
    field_names = ['Subject', 'Date', 'Path', 'Reply-to', 'Refs']
    write_csv(field_names, table, outdir)
    write_table(table, filepath)


