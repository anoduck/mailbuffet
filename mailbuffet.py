def get_header(msg):
    """Return the decoded email header."""
    header = msg.get('header')
    ret_str = str('### Header: ')
    for string, charset in decode_header(header):
        encoding = 'utf-8' if charset is None else charset
        decoded = string.decode(encoding)
        ret_str += decoded + '\n'
    return ret_str


def get_date(message):
    return parsedate_to_datetime(message['Date']).date()



def decode_part(message):
    raw = message.get_payload(decode=True)
    if raw is None:
        return ''
    charset = message.get_content_charset()
    if charset:
        try:
            return raw.decode(charset, errors='strict')
        except (LookupError, UnicodeDecodeError):
            pass
    # fallback: detect encoding
    detected = charset_normalizer.from_bytes(raw).best()
    return str(detected) if detected else raw.decode('utf-8', errors='replace')


def get_body(message):
    if message.is_multipart():
        parts = []
        for part in message.walk():
            if part.get_content_maintype() == 'multipart':
                continue
            if part.get_content_type() == 'text/plain':
                parts.append(decode_part(part))
        return '\n'.join(parts)
    else:
        return decode_part(message)


def get_author(message):
    msgfrom = message['From']
    string = [s for s, _ in decode_header(msgfrom)]
    author = ''.join(string).rsplit(maxsplit=1)[0]
    return author


def redact(content, priv):
    badwords = []
    with open(priv, 'r') as rd:
        for line in rd.readlines():
            if not line.startswith('#'):
                badwords.append(line.strip())
    for bw in badwords:
        if bw in content:
            def m(bw): return "X" * len(bw)
            content = content.replace(bw, m(bw))
    return content


def hasrefs(message):
    refs = message.get('References')
    if refs:
        return True
    else:
        return False


def parse_message(msg, priv, webpath, indexlink, outdir, log):
    body = get_body(msg)
    if body is None:
        return
    if isreply(msg):
        replyto = get_replylink(msg, webpath, outdir)
    else:
        replyto = ''
    log.debug(f'Reply To: {replyto}')
    if hasrefs(msg):
        refs = get_reflinks(msg, webpath, outdir)
    else:
        refs = ''
    log.debug(f'References: {refs}')
    content = str(f'''
{get_subject(msg)}
---
\n
<pre>
---
author: {get_author(msg)}
subject: {get_subject(msg)}
message-id: {getmid(msg)}
date: {get_date(msg)}
---
</pre>
\n
{get_body(msg)}
\n
### References
\n
{refs}
\n
### Reply-To
\n
{replyto}
\n
---
\n
[Back]({indexlink})
\n
---
\n
:END:''')
    content = redact(content, priv)
    return content


def sanitize(label):
    if isinstance(label, str):
        dirty = label
    else:
        dirty = str(label)
    splitdirty = dirty.split('.')
    phrase = splitdirty[0]
    if len(phrase) > 18:
        phrase = phrase[:18]
    undesirables = ["<", ">", "+", "=", "_", "-",
                    "'", "'", "\r", "\n", " ", "\r\n "]
    for char in undesirables:
        phrase = phrase.replace(char, '')
    return phrase


def getmid(message):
    rmid = message.get('Message-Id')
    mid = sanitize(rmid)
    return mid


def get_link(id, webpath, outdir):
    link = webpath + '/' + id + '.html'
    link = checklink(link, outdir)
    if link is not None:
        link = str(f'[{id}]({link})')
        return link
    else:
        return None


def get_filename(message):
    mid = getmid(message)
    filename = mid + '.html'
    return filename


def get_replyto(message):
    super = message.get('In-Reply-To')
    if super == ' ' or super == '' or super == None:
        return ''
    else:
        target = sanitize(super)
        return target


def get_subject(message):
    subj_raw = message.get('Subject')
    lsubj = subj_raw.lower()
    rpstr = 're:'
    rpwth = 're: '
    if rpstr in lsubj:
        subj = lsubj.replace(rpwth, '')
    else:
        subj = lsubj
    return subj


def get_ref(message):
    ref_list = []
    refs = message.get('References')
    refs = refs.split(' ')
    for ref in refs:
        if ref == ' ' or ref == '' or ref == None:
            continue
        else:
            refsan = sanitize(ref)
            ref_list.append(refsan)
    return ref_list


def get_selflink(message, webpath, outdir):
    mid = getmid(message)
    link = get_link(mid, webpath, outdir)
    return link


def get_replylink(message, webpath, outdir):
    id = get_replyto(message)
    if id == '':
        return ''
    else:
        link = get_link(id, webpath, outdir)
    return link


def get_reflinks(message, webpath, outdir):
    ref_list = get_ref(message)
    link_list = []
    for ref in ref_list:
        if ref == ' ' or ref == '' or ref == None:
            continue
        else:
            refsan = sanitize(ref)
            link = get_link(refsan, webpath, outdir)
            link_list.append(link)
    return link_list


def process_msg(msg, outdir, priv, webpath, indexlink, log):
    fname = get_filename(msg)
    log.debug(f'Filename to write: {fname}')
    fpath = os.path.join(outdir, fname)
    header = get_emailheader(fname)
    log.debug(f'Header: {header}')
    footer = get_emailfooter()
    log.debug(f'Footer: {footer}')
    with open(fpath, 'w', encoding='utf-8', errors='xmlcharrefreplace') as of:
        pcontent = str(parse_message(msg, priv, webpath, indexlink, outdir, log))
        file_text = markdown(pcontent)
        of.write(header)
        of.write(file_text)
        of.write(footer)
        of.close()


def isreply(message):
    conreply = get_replyto(message)
    subject = get_subject(message)
    if conreply:
        return True
    elif contains(subject, 're:'):
        return True
    else:
        return False


def main(Options):
    logfile = Options.log
    level = Options.lev
    global log
    log = get_log(logfile, level)
    outdir = Options.outdir
    if not os.path.isdir(outdir):
        os.mkdir(outdir)
    priv = Options.priv
    webpath = Options.webpath
    indexlink = Options.indexlink
    messages = get_mbox(Options.mbox)
    messages = list(messages)
    for msg in messages:
        process_msg(msg, outdir, priv, webpath, indexlink, log)
    generate_index(messages, outdir, webpath, log)
    print('Done!')


if __name__ == '__main__':
    main(Options)
