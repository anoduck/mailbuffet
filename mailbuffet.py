from simple_parsing import parse
from dataclasses import dataclass
from operator import contains
from mailbox import mbox
from email.header import decode_header
from email.utils import parsedate_to_datetime
from py_markdown_table.markdown_table import markdown_table
import os


@dataclass
class Options:
    """
    A more than simple script to parse the mbox file generated by Google Takeout
    into individual text files with markdown syntax.

    Script also performs redacting based on keyphrase file, a text file containing one
    keyphrase per line saved as a txt file.

    Will generate index file containing markdown_table to provide TOC to files from webpath.

    """
    mbox: str = './exported.mbox'  # Mbox file for extraction
    outdir: str = './results'  # Directory to write files to
    priv: str = ""  # File containing sensitive key phrases.
    index: bool = False  # Generate an index file
    iname: str = '_index.md'  # Name of index file to generate
    webpath: str = '/Documents/emails'  # Relative Webpath from site root


Options = parse(Options, dest='Options')


def write_table(self, table, filepath):
    mdtbl = markdown_table(table).set_params(row_sep='markdown', quote=False).get_markdown()
    with open(filepath, 'w', encoding='utf-8') as wt:
        title = "## Email Table of Contents"
        wt.write('\n')
        wt.write(title)
        wt.write('\n')
        wt.write('\n')
        wt.write(mdtbl)
        wt.write('\n')
        wt.write('\n')
        wt.write('----')
        wt.write('\n')
        wt.write('Generated by mailbuffet [Mailbuffet](https://github.com/anoduck/mailbuffet)')
        wt.close()
        print('Index written to file')

def generate_index(self, msg_list, outdir, webpath):
    filename = 'index.md'
    filepath = os.path.join(outdir, filename)
    table = []
    for msg in msg_list:
        if self.isreply(msg):
            replyto = self.get_replylink(msg, webpath)
        else:
            replyto = None
        if self.hasrefs(msg):
            refs = self.get_reflinks(msg, webpath)
        else:
            refs = None
            flink = self.get_selflink(msg, webpath)
            parent_subject = self.get_subject(msg)
            parent_date = self.get_date(msg)
            tbl_row = {"Subject": parent_subject,
                       "Date": parent_date,
                       "Path": flink,
                       "Reply-to": replyto,
                       "Refs": refs}
            table.append(tbl_row)
            self.write_table(table, filepath)


class MailBuffet:

    def __init__(self, msg):
        self.msg = msg

    def reply_to(self):
        """Return mailto parameters for replying to the given email."""
        yield 'In-Reply-To', message['Message-ID']
        yield 'Cc', message.get('Reply-To', message['From'])
        subject = message['Subject']
        if subject is None: return
        if subject.lower().startswith('re:'):
            yield 'Subject', subject
        else:
            yield 'Subject', f'Re: {subject}'

    def get_header(self, msg):
        """Return the decoded email header."""
        header = msg.get('header')
        ret_str = str('### Header: ')
        for string, charset in decode_header(header):
            encoding = 'utf-8' if charset is None else charset
            decoded = string.decode(encoding)
            ret_str += decoded + '\n'
        return ret_str

    def get_date(self):
        return parsedate_to_datetime(self.msg['Date']).date()

    def get_body(self):
        if self.msg.is_multipart():
            for payload in map(self.get_body, self.msg.get_payload()):
                if payload is not None: return payload
        elif self.msg.get_content_type() in ('text/markdown', 'text/plain'):
            payload = self.msg.get_payload(decode=True).decode()
            return payload
        else:
            return None

    def get_author(self):
        msgfrom = self.msg['From']
        string = [s for s, _ in decode_header(msgfrom)]
        author = ''.join(string).rsplit(maxsplit=1)[0]
        return author

    def redact(self, content, priv):
        badwords = []
        with open(priv, 'r') as rd:
            for line in rd.readlines():
                if not line.startswith('#'):
                    badwords.append(line.strip())
        for bw in badwords:
            if bw in content:
                def m(bw): return "X" * len(bw)
                content = content.replace(bw, m(bw))
        return content

    def hasrefs(self):
        refs = self.msg.get('References')
        if refs:
            return True
        else:
            return False

    def parse_message(self, msg, priv, webpath):
        body = self.get_body(msg)
        if body is None:
            return
        if self.isreply(msg):
            replyto = self.get_replylink(msg, webpath)
        else:
            replyto = None
        if self.hasrefs(msg):
            refs = self.get_reflinks(msg, webpath)
        else:
            refs = None
        content = str(f'''
    \n
    ---
    title: {self.get_subject(msg)}
    author: {self.get_author(msg)}
    subject: {self.get_subject(msg)}
    message-id: {self.getmid(msg)}
    date: {self.get_date(msg)}
    ---
    \n
    \n
## {self.get_subject(msg)}
    \n
    {self.get_body(msg)}
    \n
    \n
### References
    \n
    {refs}
    \n
    \n
### Reply-To
    \n
    {replyto}
    \n
    ''')
        content = self.redact(content, priv)
        return content

    def sanitize(self, phrase):
        if not isinstance(phrase, str):
            phrase = str(phrase)
        undesirables = ["<", ">", "+", "=", "_", "-", "'", "'", "\r", "\n", " ", "\r\n "]
        for char in undesirables:
            phrase = phrase.replace(char, '')
        return phrase

    def getmid(self):
        mid = self.msg.get('Message-Id')
        mid = self.sanitize(mid)
        return mid

    def get_name(self):
        mid = self.getmid(self.msg)
        name = mid + '.md'
        return name

    def get_replyto(self):
        super = self.msg.get('In-Reply-To')
        target = self.sanitize(super)
        return target

    def get_subject(self):
        subj = self.msg.get('Subject')
        return subj.lower()

    def get_ref(self):
        ref_list = []
        refs = self.msg.get('References')
        refs = refs.split(' ')
        for ref in refs:
            ref = self.sanitize(ref)
            if ref != ' ' and ref != '':
                ref_list.append(ref)
        return ref_list

    def get_selflink(self, webpath):
        mid = self.getmid(self.msg)
        link = webpath + '/' + mid
        link = str(f'[{mid}]({link})')
        return link

    def get_replylink(self, webpath):
        id = self.get_replyto(self.msg)
        link = webpath + '/' + id
        link = str(f'[{id}]({link})')
        return link

    def get_reflinks(self, webpath):
        ref_list = self.get_ref(self.msg)
        link_list = []
        for ref in ref_list:
            link = webpath + '/' + ref
            link = str(f'[{ref}]({link})')
            link_list.append(link)
        return link_list

    def process_msg(self, msg, outdir, priv, webpath):
        fname = self.get_name(msg)
        fpath = os.path.join(outdir, fname)
        with open(fpath, 'w', encoding='utf-8', errors='xmlcharrefreplace') as of:
            pcontent = str(self.parse_message(msg, priv, webpath))
            of.write(pcontent)
            of.close()

    def isreply(self):
        conreply = self.get_replyto(self.msg)
        subject = self.get_subject(self.msg)
        if conreply:
            return True
        elif contains(subject, 're:'):
            return True
        else:
            return False


def main(Options):
    outdir = Options.outdir
    if not os.path.isdir(outdir):
        os.mkdir(outdir)
    priv = Options.priv
    webpath = Options.webpath
    messages = list(mbox(Options.mbox, create=False))
    for msg in messages:
        buffet = MailBuffet(msg)
        buffet.process_msg(msg, outdir, priv, webpath)
    print('Done!')


if __name__ == '__main__':
    main(Options)
